// Generates Zod validators and their inferred TypeScript types from schema/<group>/*.json.
// It also generates the app/engine version constants used by mock fixtures; the JSON
// Schema is emitted from Rust, so this is the only hand-written step.
//
// One output module owns each schema title. A root schema belongs to the group that emitted
// it. A nested definition that appears in more than one group is emitted once in `shared`;
// a single-group definition stays in that group. Modules import across those boundaries, and
// every reference is a lazy Zod schema so a cycle is safe.
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { isDeepStrictEqual } from "node:util";
import { jsonSchemaToZod } from "json-schema-to-zod";
import prettier from "prettier";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const schemaDir = join(root, "schema");
const sourceDir = join(root, "packages", "contracts", "src");
const versionsOutput = join(sourceDir, "versions.ts");
const generatedHeader = "// @generated by packages/contracts/scripts/generate.mjs — do not edit.";
const check = process.argv.includes("--check");
// Resolve the repository's Prettier config explicitly: the API does not load a config file
// on its own, so generated output must not silently use Prettier's defaults.
const prettierOptions = (await prettier.resolveConfig(join(sourceDir, "index.ts"))) ?? {};

// Walk the feature groups under schema/. `routes/` has its own emitter and its manifest is
// not a contract schema, so it is the one directory this walk skips.
async function collect(directory) {
    const found = [];
    for (const entry of await readdir(directory, { withFileTypes: true })) {
        const path = join(directory, entry.name);
        if (entry.isDirectory()) {
            if (entry.name !== "routes") {
                found.push(...(await collect(path)));
            }
        } else if (entry.isFile() && entry.name.endsWith(".json")) {
            found.push(relative(schemaDir, path).split(sep).join("/"));
        }
    }
    return found;
}

const files = (await collect(schemaDir)).sort();
const loaded = [];
const roots = new Map();
for (const file of files) {
    const group = file.split("/")[0];
    if (group === undefined || group === file) {
        throw new Error(`${file}: a schema must live in a group directory`);
    }
    const schema = JSON.parse(await readFile(join(schemaDir, file), "utf8"));
    const title = schema.title;
    if (typeof title !== "string" || !/^[A-Z][A-Za-z0-9]*$/.test(title)) {
        throw new Error(`${file}: schema title must be a PascalCase type name`);
    }
    const previous = roots.get(title);
    if (previous !== undefined) {
        throw new Error(
            `${file}: duplicate root title ${title} (also ${previous.file}); ` +
                "root schemas must have one owner",
        );
    }
    roots.set(title, { group, file, schema });
    loaded.push({ file, group, schema, title });
}

// Schemars leaves nested models in `$defs` and points at them with `$ref`.
// json-schema-to-zod does not resolve refs, so render each reference as a lazy
// Zod schema and emit the nested models as their own named exports.
function withoutDefs(schema) {
    const copy = { ...schema };
    delete copy.$defs;
    return copy;
}

// A root document carries `$schema` and `title`; the matching `$defs` copy often carries
// neither. Identity is about the shape both share, not those document headers.
function shape(schema) {
    const copy = { ...schema };
    delete copy.$schema;
    delete copy.title;
    delete copy.$defs;
    return copy;
}

function zodBlock(title, schema, source) {
    const zodSource = jsonSchemaToZod(schema, {
        module: "esm",
        name: `${title}Schema`,
        parserOverride: (node) => {
            if (typeof node.$ref !== "string") {
                return undefined;
            }
            const name = node.$ref.replace(/^#\/\$defs\//u, "");
            if (name === node.$ref) {
                throw new Error(`unsupported $ref ${node.$ref}`);
            }
            const reference = `z.lazy(() => ${name}Schema)`;
            return typeof node.description === "string"
                ? `${reference}.describe(${JSON.stringify(node.description)})`
                : reference;
        },
    })
        .replace(/^import \{ z \} from "zod"\s*/u, "")
        .replace(/^export /u, "")
        .trim();
    return `/** ${source} */\nexport ${zodSource}\nexport type ${title} = z.infer<typeof ${title}Schema>;`;
}

// Collect every nested definition. A title may occur in several groups; all occurrences
// must describe the same shape, or a single generated type would be wrong for one of them.
const definitions = new Map();
for (const { file, group, schema } of loaded) {
    for (const [key, definition] of Object.entries(schema.$defs ?? {})) {
        const title = definition.title ?? key;
        if (typeof title !== "string" || !/^[A-Z][A-Za-z0-9]*$/u.test(title)) {
            throw new Error(`${file}: nested schema title must be a PascalCase type name`);
        }
        const entry = definitions.get(title) ?? { title, groups: new Set(), variants: [] };
        entry.groups.add(group);
        entry.variants.push({ file, schema: definition });
        definitions.set(title, entry);
    }
}

// A nested title that is also emitted as a root must be the same document; otherwise the
// root would shadow a different nested shape through the barrel.
for (const [title, entry] of definitions) {
    const rootEntry = roots.get(title);
    if (rootEntry === undefined) {
        continue;
    }
    const expected = shape(rootEntry.schema);
    for (const variant of entry.variants) {
        if (!isDeepStrictEqual(shape(variant.schema), expected)) {
            throw new Error(
                `${variant.file}: nested ${title} differs from root ${rootEntry.file}; ` +
                    "a title must have one shape",
            );
        }
    }
}
for (const [title, entry] of definitions) {
    const [first, ...rest] = entry.variants;
    if (first === undefined) {
        continue;
    }
    for (const variant of rest) {
        if (!isDeepStrictEqual(shape(variant.schema), shape(first.schema))) {
            throw new Error(
                `${variant.file}: nested ${title} differs from ${first.file}; ` +
                    "a title must have one shape",
            );
        }
    }
}

const groups = [...new Set(loaded.map((entry) => entry.group))].sort();
const ownerOf = (title) => {
    const rootEntry = roots.get(title);
    if (rootEntry !== undefined) {
        return rootEntry.group;
    }
    const definition = definitions.get(title);
    if (definition === undefined) {
        throw new Error(`no generated schema owns ${title}`);
    }
    if (definition.groups.size > 1) {
        return "shared";
    }
    const [group] = definition.groups;
    if (group === undefined) {
        throw new Error(`nested ${title} has no owning group`);
    }
    return group;
};

// Every module is built from definitions then roots. References are collected from the
// block's own document so an import is emitted only where it is used.
const blocksByOwner = new Map();
const addBlock = (owner, title, schema, source) => {
    const blocks = blocksByOwner.get(owner) ?? [];
    blocks.push({ title, schema, source });
    blocksByOwner.set(owner, blocks);
};
for (const [title, entry] of [...definitions].sort(([a], [b]) => a.localeCompare(b))) {
    if (roots.has(title)) {
        continue;
    }
    const [first] = entry.variants;
    if (first === undefined) {
        continue;
    }
    addBlock(
        ownerOf(title),
        title,
        withoutDefs(first.schema),
        `Generated from \`schema/${first.file}\`.`,
    );
}
for (const { file, group, schema, title } of loaded) {
    addBlock(group, title, withoutDefs(schema), `Generated from \`schema/${file}\`.`);
}

function referencedTitles(schema) {
    const found = new Set();
    const walk = (value) => {
        if (Array.isArray(value)) {
            value.forEach(walk);
            return;
        }
        if (value === null || typeof value !== "object") {
            return;
        }
        if (typeof value.$ref === "string") {
            const name = value.$ref.replace(/^#\/\$defs\//u, "");
            if (name === value.$ref) {
                throw new Error(`unsupported $ref ${value.$ref}`);
            }
            found.add(name);
        }
        Object.values(value).forEach(walk);
    };
    walk(schema);
    return found;
}

function modulePath(owner) {
    return join(sourceDir, ...(owner === "shared" ? ["shared"] : [owner]), "index.ts");
}

function importPath(from, owner) {
    if (owner === "shared") {
        return "../shared";
    }
    if (from === "shared") {
        return `../${owner}`;
    }
    return `../${owner}`;
}

const generated = new Map();
for (const owner of ["shared", ...groups]) {
    const blocks = blocksByOwner.get(owner) ?? [];
    if (blocks.length === 0) {
        continue;
    }
    const imports = new Map();
    for (const block of blocks) {
        for (const title of referencedTitles(block.schema)) {
            const refOwner = ownerOf(title);
            if (refOwner === owner) {
                continue;
            }
            const names = imports.get(refOwner) ?? new Set();
            names.add(`${title}Schema`);
            imports.set(refOwner, names);
        }
    }
    const importLines = [...imports]
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([target, names]) => {
            const sorted = [...names].sort().join(", ");
            return `import { ${sorted} } from "${importPath(owner, target)}";`;
        });
    const blocksSource = blocks
        .map((block) => zodBlock(block.title, block.schema, block.source))
        .join("\n\n");
    const source = `${generatedHeader}
import { z } from "zod";
${importLines.length > 0 ? `\n${importLines.join("\n")}\n` : "\n"}${blocksSource}
`;
    generated.set(modulePath(owner), {
        content: await prettier.format(source, { ...prettierOptions, parser: "typescript" }),
        label: `packages/contracts/src/${owner}/index.ts`,
    });
}

const barrelSource = `${generatedHeader}
${["shared", ...groups]
    .filter((owner) => blocksByOwner.has(owner))
    .map((owner) => `export * from "./${owner}";`)
    .join("\n")}
`;
generated.set(join(sourceDir, "index.ts"), {
    content: await prettier.format(barrelSource, { ...prettierOptions, parser: "typescript" }),
    label: "packages/contracts/src/index.ts",
});

const packageJson = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
const engineSource = await readFile(
    join(root, "rust", "crates", "engine", "src", "lib.rs"),
    "utf8",
);
const contractsSource = await readFile(
    join(root, "rust", "crates", "contracts", "src", "lib.rs"),
    "utf8",
);
const workspaceManifest = await readFile(join(root, "rust", "Cargo.toml"), "utf8");
const engineVersion = engineSource.match(/pub const ENGINE_VERSION: &str = "([^"]+)";/u)?.[1];
const apiVersion = contractsSource.match(/pub const API_VERSION: u32 = (\d+);/u)?.[1];
const engineDependency = /^\s*andean-condor\s*=\s*\{([^}]*)\}/mu.exec(workspaceManifest)?.[1];
if (engineDependency === undefined) {
    throw new Error("rust/Cargo.toml has no andean-condor dependency");
}
if (!engineDependency.includes('git = "https://github.com/BoatsMcGee/Av1an"')) {
    throw new Error("andean-condor must come from the BoatsMcGee/Av1an fork");
}
const engineRevision = /\brev = "([0-9a-f]{40})"/u.exec(engineDependency)?.[1];
if (typeof packageJson.version !== "string") {
    throw new Error("package.json has no version");
}
if (engineVersion === undefined || apiVersion === undefined) {
    throw new Error("could not read ENGINE_VERSION or API_VERSION from Rust");
}
if (engineRevision === undefined) {
    throw new Error("could not read the andean-condor rev from rust/Cargo.toml");
}
const versionsGenerated = await prettier.format(
    `${generatedHeader}
export const APP_VERSION = ${JSON.stringify(packageJson.version)};
export const ENGINE_VERSION = ${JSON.stringify(engineVersion)};
export const ENGINE_REVISION = ${JSON.stringify(engineRevision)};
export const API_VERSION = ${Number(apiVersion)};
`,
    { ...prettierOptions, parser: "typescript" },
);
generated.set(versionsOutput, {
    content: versionsGenerated,
    label: "packages/contracts/src/versions.ts",
});

// A group directory is generated-only. A stale index.ts is either an old single-group
// output or a group that no longer exists; both must fail `--check` and disappear on write.
async function staleGeneratedPaths() {
    const stale = [];
    for (const entry of await readdir(sourceDir, { withFileTypes: true })) {
        if (!entry.isDirectory() || entry.name === "fixtures") {
            continue;
        }
        const path = join(sourceDir, entry.name, "index.ts");
        const current = await readFile(path, "utf8").catch(() => "");
        if (current.startsWith(generatedHeader) && !generated.has(path)) {
            stale.push(path);
        }
    }
    return stale;
}

if (check) {
    let failed = false;
    for (const [path, target] of generated) {
        const current = await readFile(path, "utf8").catch(() => "");
        if (current !== target.content) {
            failed = true;
            console.error(`${target.label} is out of date; run npm run contracts`);
        }
    }
    for (const path of await staleGeneratedPaths()) {
        failed = true;
        console.error(
            `${relative(root, path).split(sep).join("/")} is stale; run npm run contracts`,
        );
    }
    if (failed) {
        process.exit(1);
    }
} else {
    for (const [path, target] of generated) {
        await mkdir(join(path, ".."), { recursive: true });
        await writeFile(path, target.content, "utf8");
    }
    for (const path of await staleGeneratedPaths()) {
        await rm(path);
        await rm(join(path, ".."), { recursive: false }).catch(() => {});
    }
    console.log(
        `generated ${generated.size - 1} contract modules (${groups.length} groups + shared) ` +
            `and version metadata`,
    );
}
