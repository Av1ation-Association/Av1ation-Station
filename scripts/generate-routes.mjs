// Generates the typed client path builders and the route table in docs/api.md.
// The route vocabulary itself is emitted from Rust; this script is the only hand-written
// translation step.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";

const root = fileURLToPath(new URL("../", import.meta.url));
const manifestPath = join(root, "schema", "routes", "manifest.json");
const output = join(root, "packages", "api", "src", "api", "generated", "paths.ts");
const docsPath = join(root, "docs", "api.md");
const check = process.argv.includes("--check");

const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
if (!Array.isArray(manifest.routes)) {
    throw new Error(`${manifestPath}: expected a routes array`);
}

function camelCase(value) {
    return value
        .split(/[._-]/u)
        .filter(Boolean)
        .map((part, index) => (index === 0 ? part : part[0].toUpperCase() + part.slice(1)))
        .join("");
}

function parameterName(value) {
    return value.replace(/_([a-z0-9])/gu, (_match, letter) => letter.toUpperCase());
}

function builderName(id) {
    return `${camelCase(id)}Path`;
}

function builderSource(route) {
    const params = [...route.path.matchAll(/\{([a-z][a-z0-9_]*)\}/gu)].map((match) =>
        parameterName(match[1]),
    );
    if (new Set(params).size !== params.length) {
        throw new Error(`${route.path}: duplicate path parameter`);
    }
    const signature =
        params.length === 0
            ? "()"
            : `(${params.map((name) => `${name}: string | number`).join(", ")})`;
    let cursor = 0;
    let template = "";
    for (const match of route.path.matchAll(/\{([a-z][a-z0-9_]*)\}/gu)) {
        template += route.path.slice(cursor, match.index);
        template += "${encodeURIComponent(String(" + parameterName(match[1]) + "))}";
        cursor = match.index + match[0].length;
    }
    template += route.path.slice(cursor);
    return `export const ${builderName(route.id)} = ${signature} => \`${template}\`;`;
}

const ids = new Set();
const functions = new Set();
const builders = [];
for (const route of manifest.routes) {
    if (
        typeof route.id !== "string" ||
        !/^[a-z][a-z0-9]*(?:[._-][a-z][a-z0-9]*)*$/u.test(route.id)
    ) {
        throw new Error(`${route.path}: invalid route id ${JSON.stringify(route.id)}`);
    }
    if (ids.has(route.id)) throw new Error(`duplicate route id ${route.id}`);
    ids.add(route.id);
    const name = builderName(route.id);
    if (functions.has(name)) throw new Error(`duplicate builder ${name}`);
    functions.add(name);
    if (!Array.isArray(route.methods) || route.methods.length === 0) {
        throw new Error(`${route.path}: route has no methods`);
    }
    builders.push(builderSource(route));
}

const source = `// @generated by scripts/generate-routes.mjs — do not edit.
${builders.join("\n")}
`;
const prettierOptions = (await prettier.resolveConfig(output)) ?? {};
const generated = await prettier.format(source, {
    ...prettierOptions,
    parser: "typescript",
});

const docs = await readFile(docsPath, "utf8");
const eol = docs.includes("\r\n") ? "\r\n" : "\n";
const rows = [];
for (const route of manifest.routes) {
    const path = route.path.replace(/\{([^}]+)\}/gu, ":$1");
    for (const method of route.methods) {
        if (!/^(GET|POST|PUT|PATCH|DELETE|HEAD)$/u.test(method.method)) {
            throw new Error(`${route.path}: invalid method ${method.method}`);
        }
        const purpose = String(method.purpose).replaceAll("|", "\\|");
        rows.push(`| \`${method.method}\` | \`${path}\` | ${purpose} |`);
    }
}
const table = [
    "<!-- routes:start -->",
    "| Method | Path | Purpose |",
    "| --- | --- | --- |",
    ...rows,
    "<!-- routes:end -->",
].join(eol);

let nextDocs;
if (docs.includes("<!-- routes:start -->")) {
    nextDocs = docs.replace(/<!-- routes:start -->[\s\S]*?<!-- routes:end -->/u, table);
} else {
    const header = "| Method | Path | Purpose |";
    const start = docs.indexOf(header);
    if (start === -1) throw new Error("docs/api.md has no route table header");
    const end = docs.indexOf(`${eol}${eol}`, start);
    if (end === -1) throw new Error("docs/api.md route table has no terminating blank line");
    nextDocs = `${docs.slice(0, start)}${table}${docs.slice(end)}`;
}
nextDocs = await prettier.format(nextDocs, {
    ...(await prettier.resolveConfig(docsPath)),
    parser: "markdown",
});

const targets = [
    { path: output, content: generated, label: "packages/api/src/api/generated/paths.ts" },
    { path: docsPath, content: nextDocs, label: "docs/api.md" },
];

if (check) {
    let stale = false;
    for (const target of targets) {
        const current = await readFile(target.path, "utf8").catch(() => "");
        if (current !== target.content) {
            stale = true;
            console.error(`${target.label} is out of date; run npm run routes`);
        }
    }
    if (stale) process.exit(1);
} else {
    await mkdir(join(root, "packages", "api", "src", "api", "generated"), { recursive: true });
    for (const target of targets) {
        await writeFile(target.path, target.content, "utf8");
    }
    console.log(`generated ${builders.length} path builders and ${rows.length} route rows`);
}
